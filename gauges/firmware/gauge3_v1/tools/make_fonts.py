#!/usr/bin/env python3
"""Generate 4-bit anti-aliased bitmap fonts for gauge3_v1/display (fonts.h / fonts.cpp).
Font: Barlow Condensed (SIL Open Font License). Character 0x7F is mapped to the degree sign.
Run:  python3 tools/make_fonts.py   (from the gauge3_v1 folder)"""
import os
from PIL import Image, ImageDraw, ImageFont
FD = "/usr/share/fonts/truetype/sand-box/google/Barlow Condensed/"
ASCII = "".join(chr(c) for c in range(32, 127)) + "\x7f"
DIGITS = " +,-.0123456789%\x7f"
FONTS = [  # name, ttf, pixel size, charset
    ("FONT_BIG",  "BarlowCondensed-Bold.ttf",     150, DIGITS),
    ("FONT_BIG2", "BarlowCondensed-Bold.ttf",     108, DIGITS),
    ("FONT_L",    "BarlowCondensed-ExtraBold.ttf", 58, ASCII),
    ("FONT_M",    "BarlowCondensed-SemiBold.ttf",  38, ASCII),
    ("FONT_S",    "BarlowCondensed-SemiBold.ttf",  28, ASCII),
]
here = os.path.dirname(os.path.abspath(__file__))
outdir = os.path.join(here, "..", "display")
h = ["// GENERATED by tools/make_fonts.py - do not edit", "#pragma once", '#include "gfx.h"']
c = ["// GENERATED by tools/make_fonts.py - do not edit", '#include "fonts.h"']
for name, ttf, size, chars in FONTS:
    f = ImageFont.truetype(FD + ttf, size)
    asc, desc = f.getmetrics()
    bmp = bytearray(); glyphs = []
    for code in range(32, 128):
        ch = chr(code); real = "\u00b0" if code == 0x7F else ch
        if ch not in chars:
            glyphs.append((0, 0, 0, 0, 0, 0)); continue
        adv = int(round(f.getlength(real)))
        im = Image.new("L", (size * 2, size * 2), 0)
        d = ImageDraw.Draw(im)
        ox, oy = size // 2, size  # baseline origin
        d.text((ox, oy), real, font=f, fill=255, anchor="ls")
        bb = im.getbbox()
        if bb is None:
            glyphs.append((len(bmp), 0, 0, 0, 0, adv)); continue
        x0, y0, x1, y1 = bb
        w, hh = x1 - x0, y1 - y0
        off = len(bmp)
        px = im.crop(bb).tobytes()
        nib = [(p + 8) // 17 for p in px]
        if len(nib) % 2: nib.append(0)
        for i in range(0, len(nib), 2): bmp.append((nib[i] << 4) | nib[i + 1])
        glyphs.append((off, w, hh, x0 - ox, y0 - oy, adv))
    lname = name.lower()
    c.append(f"static const uint8_t {lname}_bmp[{len(bmp)}] = {{")
    for i in range(0, len(bmp), 24):
        c.append("  " + ",".join(str(b) for b in bmp[i:i + 24]) + ",")
    c.append("};")
    c.append(f"static const Glyph {lname}_glyphs[96] = {{")
    for g in glyphs: c.append("  {%d,%d,%d,%d,%d,%d}," % g)
    c.append("};")
    c.append(f"const Font {name} = {{ {lname}_bmp, {lname}_glyphs, {asc}, {desc} }};")
    h.append(f"extern const Font {name};   // {ttf} {size}px, {len(bmp)} bytes")
    print(name, len(bmp), "bytes")
open(os.path.join(outdir, "fonts.h"), "w").write("\n".join(h) + "\n")
open(os.path.join(outdir, "fonts.cpp"), "w").write("\n".join(c) + "\n")
